/** Per-glyph horizontal trims: narrow characters should not sit in a 5- or
 *  7-wide box or the line reads as a monospaced terminal dump. */
const SMALL_TRIM = {
  ' ': [1, 2], '1': [1, 1], '!': [2, 2], '.': [1, 2], ',': [1, 2], ':': [1, 2],
  "'": [2, 2], 'I': [1, 1], '(': [1, 1], ')': [1, 1], '-': [0, 0],
};
const DISPLAY_TRIM = {
  ' ': [2, 2], '1': [1, 1], '!': [3, 2], '.': [3, 2], ':': [3, 2], 'I': [1, 1],
};

function buildFace(glyphs, w, h, trims, tracking) {
  const table = new Map();
  for (const [ch, rows] of Object.entries(glyphs)) {
    if (rows.length !== h) throw new Error(`glyph "${ch}": ${rows.length} rows, expected ${h}`);
    const mask = [];
    for (const row of rows) {
      if (row.length !== w) throw new Error(`glyph "${ch}": row "${row}" is ${row.length} wide, expected ${w}`);
      mask.push(row);
    }
    const [l, r] = trims[ch] || [0, 0];
    table.set(ch, { mask, left: l, width: w - l - r });
  }
  return { glyphs: table, w, h, tracking };
}

export const SMALL = buildFace(SMALL_GLYPHS, 5, 7, SMALL_TRIM, 1);
export const DISPLAY = buildFace(DISPLAY_GLYPHS, 7, 10, DISPLAY_TRIM, 1);

const hexRgb = (h) => [(h >> 16) & 255, (h >> 8) & 255, h & 255];

function glyphFor(face, ch) {
  return face.glyphs.get(ch) || face.glyphs.get(ch.toUpperCase()) || face.glyphs.get(' ');
}

/** Width in texels of `text` in `face`, excluding any outline/shadow padding. */
export function measure(text, face = SMALL) {
  let w = 0;
  for (let i = 0; i < text.length; i++) {
    w += glyphFor(face, text[i]).width + (i < text.length - 1 ? face.tracking : 0);
  }
  return w;
}

/**
 * Composite a string into a PixBuf.
 *
 * `ramp` colours the glyph by row rather than flat, which is how arcade
 * lettering gets its metal look; `outline` wraps the silhouette so the text
 * survives landing on a bright fruit, and `shadow` drops a single offset copy.
 */
export function textBuf(text, {
  face = SMALL, colour = 0xffffff, ramp = null, outline = null, shadow = null,
} = {}) {
  const pad = outline !== null ? 1 : 0;
  const sx = pad;
  const sy = pad;
  const shadowOff = shadow !== null ? 1 : 0;
  const w = measure(text, face) + pad * 2 + shadowOff;
  const h = face.h + pad * 2 + shadowOff;
  const buf = new PixBuf(Math.max(1, w), h);

  const fill = ramp ? ramp.map(hexRgb) : null;
  const flat = hexRgb(colour);
  const rowColour = (row) => (fill ? fill[Math.min(fill.length - 1, row)] : flat);

  const stamp = (ox, oy, colourAt) => {
    let x = ox;
    for (let i = 0; i < text.length; i++) {
      const g = glyphFor(face, text[i]);
      for (let row = 0; row < face.h; row++) {
        const line = g.mask[row];
        for (let col = 0; col < g.width; col++) {
          if (line[col + g.left] === '#') buf.set(x + col, oy + row, colourAt(row));
        }
      }
      x += g.width + face.tracking;
    }
  };

  if (shadow !== null) {
    const s = hexRgb(shadow);
    stamp(sx + 1, sy + 1, () => s);
  }
  if (outline !== null) {
    // Stamp the glyphs into a scratch buffer first so the outline hugs the
    // whole word, not each letter — kerned pairs must not grow a seam.
    const ink = new PixBuf(buf.w, buf.h);
    const save = buf.data;
    buf.data = ink.data;
    stamp(sx, sy, () => [255, 255, 255]);
    buf.data = save;
    ink.outline(hexRgb(outline));
    for (let y = 0; y < buf.h; y++) {
      for (let x = 0; x < buf.w; x++) {
        if (ink.alpha(x, y) && !(ink.get(x, y)[0] === 255 && ink.get(x, y)[1] === 255 && ink.get(x, y)[2] === 255)) {
          buf.set(x, y, ink.get(x, y).slice(0, 3));
        }
      }
    }
  }
  stamp(sx, sy, rowColour);
  return buf;
}

/** Upload a PixBuf as a nearest-filtered texture. */
export function bufTexture(buf) {
  const source = new ImageSource({
    resource: buf.toCanvas(),
    scaleMode: 'nearest',
    alphaMode: 'premultiply-alpha-on-upload',
  });
  return new Texture({ source, frame: new Rectangle(0, 0, buf.w, buf.h) });
}

/**
 * A sprite that draws a string in a bitmap face.
 *
 * The texture is rebuilt only when the string or style actually changes, so a
 * score that ticks once a second costs one small upload a second and nothing
 * in between. `align` shifts the sprite by whole texels only.
 */
export class BitmapText extends Sprite {
  constructor(opts = {}) {
    super(Texture.EMPTY);
    this.opts = { face: SMALL, colour: 0xffffff, align: 'left', ...opts };
    this._key = null;
    this._anchorX = { left: 0, center: 0.5, right: 1 }[this.opts.align] ?? 0;
    if (opts.text) this.text = opts.text;
  }

  set text(value) {
    const str = String(value);
    if (str === this._key) return;
    this._key = str;
    if (this.texture !== Texture.EMPTY) this.texture.destroy(true);
    const buf = textBuf(str, this.opts);
    this.texture = bufTexture(buf);
    // Alignment is an integer pivot, never a fractional anchor: anchor 0.5 on
    // an odd-width texture lands the sprite on a half texel and goes soft.
    // The pivot is placed on the ink box, so `x`/`y` always mean "top-left of
    // the letters" regardless of outline padding.
    const pad = this.opts.outline != null ? 1 : 0;
    const inkW = buf.w - pad * 2 - (this.opts.shadow != null ? 1 : 0);
    this.pivot.x = pad + Math.round(inkW * this._anchorX);
    this.pivot.y = pad;
    this.inkWidth = inkW;
  }

  get text() { return this._key; }

  /** Restyle in place; forces a rebuild on the next assignment. */
  restyle(patch) {
    this.opts = { ...this.opts, ...patch };
    const t = this._key;
    this._key = null;
    if (t !== null) this.text = t;
  }
}
